import { chromium } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';

const source = await readFile('output/people-motion-concept.html', 'utf8');
assert(!source.includes('\\"'), 'Literal HTML attributes');
new Function(source.match(/<script>([\s\S]*?)<\/script>/)[1]);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 768, height: 900 }, colorScheme: 'dark' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(pathToFileURL(`${process.cwd()}/tmp/people-motion-preview.html`).href);
const frame = page.frameLocator('iframe');
const root = frame.locator('#nucleus-cast-concept');
await root.waitFor();
assert.equal(await frame.locator('.nc-member').count(), 15);
await root.screenshot({ path: 'tmp/people-concept-gather.png' });
const slider = frame.locator('#nc-progress');
await slider.fill('520');
await slider.dispatchEvent('change');
assert.equal(await slider.inputValue(), '520');
assert.equal(await frame.locator('[data-name]').textContent(), 'Mohit');
await root.screenshot({ path: 'tmp/people-concept-spotlight.png' });
await frame.getByRole('button', { name: 'Play the motion concept', exact: true }).click();
await page.waitForTimeout(450);
await frame.getByRole('button', { name: 'Pause the motion concept', exact: true }).click();
assert(Number(await slider.inputValue()) > 520, 'Playback must advance');
await slider.fill('1000');
assert.equal(await frame.locator('.nc-roster article').count(), 15);
await root.screenshot({ path: 'tmp/people-concept-together.png' });
await page.setViewportSize({ width: 352, height: 1100 });
await page.waitForTimeout(100);
const box = await root.boundingBox();
assert(box.width <= 320.5, 'Mobile surface fits available width');
const overflow = await root.evaluate(el => ({ scroll: el.scrollWidth, width: el.clientWidth }));
assert(overflow.scroll <= overflow.width + 1, 'No horizontal overflow');
await root.screenshot({ path: 'tmp/people-concept-mobile.png' });
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.waitForTimeout(100);
assert.equal(await slider.inputValue(), '1000');
assert.deepEqual(errors, []);
console.log(JSON.stringify({ cards: 15, scrubbing: 'passed', playback: 'passed', mobile: 'passed', reducedMotion: 'passed', pageErrors: errors }));
await browser.close();
